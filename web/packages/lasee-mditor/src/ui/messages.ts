export const LOCALES: Record<Locale, Messages> = { ko, en };

/** {이름} 자리를 채운다. */
export function fill(s: string, vars?: Record<string, string | number>): string {
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

export function messagesFor(locale: Locale = "ko", over?: Partial<Messages>): Messages {
  return { ...(LOCALES[locale] ?? ko), ...(over ?? {}) };
}
